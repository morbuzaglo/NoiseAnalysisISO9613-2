clear
clc
close all

%% ============================================================
%  USER SETTINGS
% =============================================================

functionsFolder = fullfile(pwd,'functions');
addpath(functionsFolder);

%% ------------------------------------------------------------
%  SOURCE MODEL
% ------------------------------------------------------------

sourceModelFile = ...
    fullfile(pwd,'experiment','source_model.mat');

outputFolder = ...
    fullfile(pwd,'prediction_results');

if ~exist(outputFolder,'dir')
    mkdir(outputFolder);
end

outputExcel = ...
    fullfile(outputFolder,'noise_prediction.xlsx');

%% ------------------------------------------------------------
%  NEW ENVIRONMENT
% ------------------------------------------------------------

T_C = 25;
RH = 60;
p = 101325;
c = 343;

%% ------------------------------------------------------------
%  NEW RECEIVER
% ------------------------------------------------------------

theta_receiver = 70;

receiverHeightAboveGround = 1.5;

%% ------------------------------------------------------------
%  GROUND
% ------------------------------------------------------------

G_s = 1;
G_m = 1;
G_r = 1;

%% ------------------------------------------------------------
%  REFLECTING SURFACES
% ------------------------------------------------------------

D_surface = 0;

%% ------------------------------------------------------------
%  BACKGROUND MODEL
% ------------------------------------------------------------

backgroundModel = 'typical';

% For typical:
typicalEnvironment = 'rural';

% For Illinois:
IllinoisCategory = 5;
IllinoisTime = 'night';

%% ============================================================
%  LOAD SOURCE MODEL
% =============================================================

data = load(sourceModelFile);

sourceModel = data.sourceModel;

f = sourceModel.f;
L_W = sourceModel.L_W;

calibAnglesDeg = ...
    sourceModel.calibAnglesDeg;

D_source = ...
    sourceModel.D_source;

h_s = ...
    sourceModel.h_s;

nFreq = length(f);

fprintf('\n============================================\n')
fprintf('SOURCE MODEL LOADED\n')
fprintf('============================================\n')

disp(table( ...
    f.', ...
    L_W.', ...
    'VariableNames',{'f_Hz','L_W_dB'}))

%% ============================================================
%  DEFINE NEW TERRAIN
% =============================================================

xTerrain = linspace(0,500,1001);

zTerrain = ...
      5*exp(-((xTerrain-90)/40).^2) ...
    +14*exp(-((xTerrain-220)/32).^2) ...
    - 6*exp(-((xTerrain-320)/55).^2) ...
    + 9*exp(-((xTerrain-410)/38).^2);

sourceX = 0;
receiverX = 500;

sourceGround = ...
    interp1( ...
        xTerrain, ...
        zTerrain, ...
        sourceX);

receiverGround = ...
    interp1( ...
        xTerrain, ...
        zTerrain, ...
        receiverX);

S = ...
    [sourceX ...
     sourceGround+h_s];

R = ...
    [receiverX ...
     receiverGround+receiverHeightAboveGround];

%% ============================================================
%  TERRAIN DIFFRACTION
% =============================================================

edges = ...
    find_terrain_diffraction_Edges_2D( ...
        S,R,xTerrain,zTerrain);

[z,d_ss,d_sr,e,d,L_diff] = ...
    z_multiEdge_2D( ...
        S,R,edges);

d_p = ...
    abs(receiverX-sourceX);

fprintf('\n============================================\n')
fprintf('NEW GEOMETRY\n')
fprintf('============================================\n')

fprintf('Horizontal distance = %.3f m\n',d_p)
fprintf('Direct distance     = %.3f m\n',d)
fprintf('Diffracted path     = %.3f m\n',L_diff)
fprintf('Path difference z   = %.6f m\n',z)

fprintf('\nDiffraction edges:\n')
disp(edges)

%% ============================================================
%  PROPAGATION ATTENUATIONS
% =============================================================

A_div_scalar = ...
    calc_Atten_div(d);

A_div = ...
    A_div_scalar .* ones(1,nFreq);

[A_atm,alpha] = ...
    calc_Atten_atm( ...
        f,T_C,RH,p,d);

[A_gr,~,~,~] = ...
    calc_Atten_gr( ...
        f, ...
        h_s, ...
        receiverHeightAboveGround, ...
        d_p, ...
        G_s, ...
        G_m, ...
        G_r);

%% ============================================================
%  BARRIER / TERRAIN
% =============================================================

diffractionType = 'top';

if isempty(edges)

    A_bar = zeros(1,nFreq);
    D_z = zeros(1,nFreq);

else

    [A_bar,D_z,K_met,C3,z_min] = ...
        calc_Atten_bar( ...
            f, ...
            c, ...
            z, ...
            e, ...
            d_ss, ...
            d_sr, ...
            d, ...
            A_gr, ...
            diffractionType);

end

%% ============================================================
%  SOURCE DIRECTIVITY
% =============================================================

D_source_receiver = ...
    estimate_Dsource_at_angle( ...
        calibAnglesDeg, ...
        D_source, ...
        theta_receiver);

if isscalar(D_surface)
    D_surface = ...
        D_surface .* ones(1,nFreq);
end

%% ============================================================
%  SOURCE PREDICTION
% =============================================================

[Lp_source,D_source_check] = ...
    predict_Lp_at_mic( ...
        f, ...
        L_W, ...
        theta_receiver, ...
        calibAnglesDeg, ...
        D_source, ...
        D_surface, ...
        A_div, ...
        A_atm, ...
        A_gr, ...
        A_bar);

%% ============================================================
%  BACKGROUND
% =============================================================

switch lower(backgroundModel)

    case 'typical'

        [~,Lp_background,LpA_background,bgDescription] = ...
            get_background_spectrum_typical( ...
                typicalEnvironment);

    case 'illinois'

        [~,Lp_background,LpA_background,bgDescription] = ...
            get_background_spectrum_Illinois_regulation( ...
                IllinoisCategory, ...
                IllinoisTime);

    otherwise

        error( ...
            'backgroundModel must be ''typical'' or ''illinois''.');

end

%% ============================================================
%  SOURCE + BACKGROUND
% =============================================================

Lp_total = ...
    10*log10( ...
        10.^(Lp_source/10) + ...
        10.^(Lp_background/10));

%% ============================================================
%  A-WEIGHTED TOTALS
% =============================================================

A_weight = ...
    [-26.2 -16.1 -8.6 -3.2 0 1.2 1.0 -1.1];

LpA_source = ...
    10*log10(sum( ...
        10.^((Lp_source+A_weight)/10)));

LpA_total = ...
    10*log10(sum( ...
        10.^((Lp_total+A_weight)/10)));

%% ============================================================
%  RESULTS
% =============================================================

PredictionTable = table( ...
    f.', ...
    L_W.', ...
    D_source_receiver.', ...
    A_div.', ...
    A_atm.', ...
    A_gr.', ...
    D_z.', ...
    A_bar.', ...
    Lp_source.', ...
    Lp_background.', ...
    Lp_total.', ...
    'VariableNames',{ ...
        'f_Hz', ...
        'L_W', ...
        'D_source', ...
        'A_div', ...
        'A_atm', ...
        'A_gr', ...
        'D_z', ...
        'A_bar', ...
        'Lp_source', ...
        'Lp_background', ...
        'Lp_total'});

fprintf('\n============================================\n')
fprintf('PREDICTION RESULTS\n')
fprintf('============================================\n')

disp(PredictionTable)

fprintf('Source contribution = %.2f dBA\n',LpA_source)
fprintf('Background          = %.2f dBA\n',LpA_background)
fprintf('Combined level      = %.2f dBA\n',LpA_total)

fprintf('\nBackground model:\n%s\n',bgDescription)

%% ============================================================
%  PLOT 1 - TERRAIN
% =============================================================

figure

plot( ...
    xTerrain, ...
    zTerrain, ...
    'LineWidth',1.5)

hold on

plot( ...
    S(1),S(2), ...
    'o', ...
    'MarkerSize',8, ...
    'DisplayName','Source')

plot( ...
    R(1),R(2), ...
    's', ...
    'MarkerSize',8, ...
    'DisplayName','Receiver')

if ~isempty(edges)

    plot( ...
        edges(:,1), ...
        edges(:,2), ...
        'x', ...
        'MarkerSize',9, ...
        'LineWidth',1.5, ...
        'DisplayName','Diffraction edges')

    pathPoints = ...
        [S;edges;R];

    plot( ...
        pathPoints(:,1), ...
        pathPoints(:,2), ...
        '--', ...
        'LineWidth',1.2, ...
        'DisplayName','Diffracted path')

end

grid on
xlabel('Distance x [m]')
ylabel('Elevation z [m]')
title('Terrain and diffraction geometry')
legend('Location','best')

%% ============================================================
%  PLOT 2 - PROPAGATION TERMS
% =============================================================

figure

semilogx( ...
    f,A_atm, ...
    'o-', ...
    'LineWidth',1.5)

hold on

semilogx( ...
    f,A_gr, ...
    's-', ...
    'LineWidth',1.5)

semilogx( ...
    f,A_bar, ...
    '^-', ...
    'LineWidth',1.5)

grid on
xlabel('Frequency [Hz]')
ylabel('Attenuation [dB]')
title('Propagation attenuation')
legend( ...
    'A_{atm}', ...
    'A_{gr}', ...
    'A_{bar}', ...
    'Location','best')

%% ============================================================
%  PLOT 3 - SOURCE / BACKGROUND / TOTAL
% =============================================================

figure

semilogx( ...
    f,Lp_source, ...
    'o-', ...
    'LineWidth',1.5)

hold on

semilogx( ...
    f,Lp_background, ...
    's-', ...
    'LineWidth',1.5)

semilogx( ...
    f,Lp_total, ...
    '^-', ...
    'LineWidth',1.5)

grid on
xlabel('Frequency [Hz]')
ylabel('L_p [dB]')
title('Predicted sound at receiver')
legend( ...
    'Source', ...
    'Background', ...
    'Combined', ...
    'Location','best')

%% ============================================================
%  SUMMARY TABLE
% =============================================================

SummaryTable = table( ...
    d_p, ...
    d, ...
    theta_receiver, ...
    receiverHeightAboveGround, ...
    LpA_source, ...
    LpA_background, ...
    LpA_total, ...
    'VariableNames',{ ...
        'HorizontalDistance_m', ...
        'DirectDistance_m', ...
        'ReceiverAngle_deg', ...
        'ReceiverHeight_m', ...
        'Source_dBA', ...
        'Background_dBA', ...
        'Combined_dBA'});

%% ============================================================
%  EXPORT EXCEL
% =============================================================

if isfile(outputExcel)
    delete(outputExcel)
end

writetable( ...
    SummaryTable, ...
    outputExcel, ...
    'Sheet','Summary');

writetable( ...
    PredictionTable, ...
    outputExcel, ...
    'Sheet','Spectrum');

TerrainTable = table( ...
    xTerrain.', ...
    zTerrain.', ...
    'VariableNames',{ ...
        'x_m', ...
        'z_m'});

writetable( ...
    TerrainTable, ...
    outputExcel, ...
    'Sheet','Terrain');

if ~isempty(edges)

    EdgeTable = table( ...
        edges(:,1), ...
        edges(:,2), ...
        'VariableNames',{ ...
            'x_m', ...
            'z_m'});

    writetable( ...
        EdgeTable, ...
        outputExcel, ...
        'Sheet','Diffraction Edges');

end

fprintf('\n============================================\n')
fprintf('PREDICTION SAVED\n')
fprintf('============================================\n')

fprintf('%s\n',outputExcel)