clear
clc
close all

%% ============================================================
%  USER SETTINGS
% =============================================================

experimentFolder = fullfile(pwd,'experiment');
functionsFolder = fullfile(pwd,'functions');

addpath(functionsFolder);

%% Files

outputMAT = fullfile(experimentFolder,'source_model.mat');
outputExcel = fullfile(experimentFolder,'experiment_analysis.xlsx');

%% Frequency bands

f = [63 125 250 500 1000 2000 4000 8000];

nFreq = length(f);

%% ------------------------------------------------------------
%  MICROPHONES TO USE
% ------------------------------------------------------------

% All microphones that belong to this experiment:
micsToUse = 1:13;

% Close microphones used to estimate L_W and source directivity:
closeMics = [1 2 3 6 7 8 10 11 12];

% Far microphones used ONLY for validation:
farMics = [4 5 9 13];

% Make sure sets are valid:
if any(~ismember(closeMics,micsToUse))
    error('All closeMics must be included in micsToUse.');
end

if any(~ismember(farMics,micsToUse))
    error('All farMics must be included in micsToUse.');
end

if ~isempty(intersect(closeMics,farMics))
    error('closeMics and farMics must not overlap.');
end

%% ------------------------------------------------------------
%  ANALYSIS WINDOWS
% ------------------------------------------------------------

% Source ON:
t_source = [5 15];

% Background only:
t_background = [0 5];

%% ------------------------------------------------------------
%  ENVIRONMENT
% ------------------------------------------------------------

T_C = 20;
RH = 70;
p = 101325;
c = 343;

%% ------------------------------------------------------------
%  SOURCE GEOMETRY
% ------------------------------------------------------------

h_s = 1.5;

%% ------------------------------------------------------------
%  MICROPHONE GEOMETRY
% ------------------------------------------------------------

% One value per microphone number.

d_p_all = ...
    [7 14 21 50 250 ...
     7 14 21 50 ...
     7 14 21 50];

h_r_all = ...
    [1.5 1.5 1.5 1.5 -11 ...
     1.5 1.5 1.5 1.5 ...
     1.5 1.5 1.5 1.5];

theta_all = ...
    [0 0 0 0 0 ...
     120 120 120 120 ...
     240 240 240 240];

%% ------------------------------------------------------------
%  GROUND PARAMETERS
% ------------------------------------------------------------

G_s_all = ones(1,13);
G_m_all = ones(1,13);
G_r_all = ones(1,13);

%% ------------------------------------------------------------
%  SURFACE DIRECTIVITY
% ------------------------------------------------------------

D_surface_all = zeros(13,nFreq);

%% ------------------------------------------------------------
%  BARRIER / TOPOGRAPHY ATTENUATION
% ------------------------------------------------------------

% Default:
A_bar_all = zeros(13,nFreq);

% Examples of manual values:
%
% A_bar_all(5,:) = [0 0 1 3 6 9 12 15];
%
% Later this can be replaced by calculations from:
% find_terrain_diffraction_Edges_2D
% z_multiEdge_2D
% calc_Atten_bar

%% ============================================================
%  INITIAL CHECKS
% =============================================================

nTotalMics = length(d_p_all);

if length(h_r_all) ~= nTotalMics || ...
   length(theta_all) ~= nTotalMics
    error('Microphone geometry vectors must have equal length.');
end

if max(micsToUse) > nTotalMics
    error('micsToUse contains a microphone outside the geometry arrays.');
end

%% ============================================================
%  LOAD AND ANALYZE RECORDINGS
% =============================================================

Lp_total_all = nan(nTotalMics,nFreq);
Lp_bg_all = nan(nTotalMics,nFreq);
fs_all = nan(nTotalMics,1);

fprintf('\n============================================\n')
fprintf('EXPERIMENT DATA ANALYSIS\n')
fprintf('============================================\n')

for mic = micsToUse

    fileName = sprintf('mic_%03d.mat',mic);
    filePath = fullfile(experimentFolder,fileName);

    if ~isfile(filePath)
        error('Missing microphone file: %s',filePath);
    end

    data = load(filePath);

    if ~isfield(data,'sig') || ~isfield(data,'fs')
        error('%s must contain sig and fs.',fileName);
    end

    sig = data.sig(:);
    fs = data.fs;

    fs_all(mic) = fs;

    %% Use file geometry if available

    if isfield(data,'dist')
        d_p_all(mic) = data.dist;
    end

    if isfield(data,'line')
        theta_all(mic) = data.line;
    end

    %% Calculate octave-band SPL

    Lp_total_all(mic,:) = ...
        calc_Lp_total( ...
            sig,fs,f, ...
            t_source(1), ...
            t_source(2), ...
            'octave');

    Lp_bg_all(mic,:) = ...
        calc_Lp_bg( ...
            sig,fs,f, ...
            t_background(1), ...
            t_background(2), ...
            'octave');

    fprintf( ...
        'Mic %02d | d_p = %7.2f m | h = %7.2f m | theta = %7.2f deg\n', ...
        mic,d_p_all(mic),h_r_all(mic),theta_all(mic));

end

%% ============================================================
%  CLOSE MICROPHONES - SOURCE CHARACTERIZATION
% =============================================================

d_p_close = d_p_all(closeMics);
h_r_close = h_r_all(closeMics);

d_close = sqrt( ...
    d_p_close.^2 + ...
    (h_s-h_r_close).^2);

theta_close = theta_all(closeMics);

Lp_total_close = Lp_total_all(closeMics,:);
Lp_bg_close = Lp_bg_all(closeMics,:);

G_s_close = G_s_all(closeMics);
G_m_close = G_m_all(closeMics);
G_r_close = G_r_all(closeMics);

D_surface_close = D_surface_all(closeMics,:);

%% Estimate L_W and source directivity

[L_W,L_W_std,L_W_mics,D_source_raw, ...
 Lp_source_close,validBG_close] = ...
    estimate_Lw_from_close_mics( ...
        f, ...
        Lp_total_close, ...
        Lp_bg_close, ...
        d_close, ...
        d_p_close, ...
        h_s, ...
        h_r_close, ...
        G_s_close, ...
        G_m_close, ...
        G_r_close, ...
        T_C, ...
        RH, ...
        p, ...
        D_surface_close, ...
        theta_close);

%% ============================================================
%  COLLAPSE REPEATED ANGLES
% =============================================================

calibAnglesDeg = unique(theta_close(:));

D_source = nan(length(calibAnglesDeg),nFreq);

for i = 1:length(calibAnglesDeg)

    idx = theta_close(:) == calibAnglesDeg(i);

    D_source(i,:) = ...
        mean(D_source_raw(idx,:),1,'omitnan');

end

%% ============================================================
%  SOURCE RESULTS
% =============================================================

fprintf('\n============================================\n')
fprintf('SOURCE CHARACTERIZATION\n')
fprintf('============================================\n')

SourceTable = table( ...
    f.', ...
    L_W.', ...
    L_W_std.', ...
    'VariableNames',{ ...
        'f_Hz', ...
        'L_W_dB', ...
        'Std_dB'});

disp(SourceTable)

DirectivityTable = ...
    array2table( ...
        D_source, ...
        'VariableNames',compose('Hz_%d',f));

DirectivityTable.Angle_deg = calibAnglesDeg(:);

DirectivityTable = ...
    movevars( ...
        DirectivityTable, ...
        'Angle_deg', ...
        'Before',1);

disp(DirectivityTable)

%% ============================================================
%  PRECALCULATE ATTENUATIONS FOR FAR MICROPHONES
% =============================================================

nFar = length(farMics);

d_p_far = d_p_all(farMics);
h_r_far = h_r_all(farMics);
theta_far = theta_all(farMics);

d_far = sqrt( ...
    d_p_far.^2 + ...
    (h_s-h_r_far).^2);

Lp_total_far = Lp_total_all(farMics,:);
Lp_bg_far = Lp_bg_all(farMics,:);

D_surface_far = D_surface_all(farMics,:);

A_div_far = nan(nFar,nFreq);
A_atm_far = nan(nFar,nFreq);
A_gr_far = nan(nFar,nFreq);
A_bar_far = A_bar_all(farMics,:);

for i = 1:nFar

    A_div_i = ...
        calc_Atten_div(d_far(i));

    A_div_far(i,:) = ...
        A_div_i .* ones(1,nFreq);

    [A_atm_far(i,:),~] = ...
        calc_Atten_atm( ...
            f,T_C,RH,p,d_far(i));

    [A_gr_far(i,:),~,~,~] = ...
        calc_Atten_gr( ...
            f, ...
            h_s, ...
            h_r_far(i), ...
            d_p_far(i), ...
            G_s_all(farMics(i)), ...
            G_m_all(farMics(i)), ...
            G_r_all(farMics(i)));

end

%% ============================================================
%  VALIDATION
% =============================================================

results = ...
    validate_far_mics( ...
        f, ...
        L_W, ...
        calibAnglesDeg, ...
        D_source, ...
        Lp_total_far, ...
        Lp_bg_far, ...
        theta_far, ...
        D_surface_far, ...
        A_div_far, ...
        A_atm_far, ...
        A_gr_far, ...
        A_bar_far);

%% ============================================================
%  VALIDATION SUMMARY TABLE
% =============================================================

ValidationSummary = table( ...
    farMics(:), ...
    d_p_far(:), ...
    d_far(:), ...
    h_r_far(:), ...
    theta_far(:), ...
    results.Bias, ...
    results.MAE, ...
    results.RMSE, ...
    results.LpA_measured, ...
    results.LpA_predicted, ...
    results.Delta_LA, ...
    'VariableNames',{ ...
        'Mic', ...
        'HorizontalDistance_m', ...
        'DirectDistance_m', ...
        'ReceiverHeight_m', ...
        'Angle_deg', ...
        'Bias_dB', ...
        'MAE_dB', ...
        'RMSE_dB', ...
        'Measured_dBA', ...
        'Predicted_dBA', ...
        'Delta_dBA'});

fprintf('\n============================================\n')
fprintf('VALIDATION SUMMARY\n')
fprintf('============================================\n')

disp(ValidationSummary)

%% ============================================================
%  VALIDATION BY FREQUENCY
% =============================================================

ValidationFrequency = table( ...
    f.', ...
    results.Bias_freq.', ...
    results.MAE_freq.', ...
    results.RMSE_freq.', ...
    'VariableNames',{ ...
        'f_Hz', ...
        'Bias_dB', ...
        'MAE_dB', ...
        'RMSE_dB'});

disp(ValidationFrequency)

%% ============================================================
%  PLOT 1 - MEASURED VS PREDICTED
% =============================================================

colors = lines(nFar);

figure
hold on

for i = 1:nFar

    semilogx( ...
        f, ...
        results.Lp_measured(i,:), ...
        'o-', ...
        'Color',colors(i,:), ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Mic %d measured',farMics(i)));

    semilogx( ...
        f, ...
        results.Lp_predicted(i,:), ...
        '--', ...
        'Color',colors(i,:), ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Mic %d predicted',farMics(i)));

end

grid on
xlabel('Frequency [Hz]')
ylabel('L_p [dB]')
title('Measured vs predicted')
legend('Location','best')

%% ============================================================
%  PLOT 2 - ERROR BY MIC
% =============================================================

figure
hold on

for i = 1:nFar

    semilogx( ...
        f, ...
        results.Delta_L(i,:), ...
        'o-', ...
        'Color',colors(i,:), ...
        'LineWidth',1.5, ...
        'DisplayName', ...
        sprintf('Mic %d',farMics(i)));

end

yline(0,'--')

grid on
xlabel('Frequency [Hz]')
ylabel('\DeltaL = Measured - Predicted [dB]')
title('Prediction error by microphone')
legend('Location','best')

%% ============================================================
%  PLOT 3 - ERROR STATISTICS BY FREQUENCY
% =============================================================

figure
hold on

semilogx( ...
    f,results.Bias_freq, ...
    'o-', ...
    'LineWidth',1.5, ...
    'DisplayName','Bias');

semilogx( ...
    f,results.MAE_freq, ...
    's-', ...
    'LineWidth',1.5, ...
    'DisplayName','MAE');

semilogx( ...
    f,results.RMSE_freq, ...
    '^-', ...
    'LineWidth',1.5, ...
    'DisplayName','RMSE');

yline(0,'--')

grid on
xlabel('Frequency [Hz]')
ylabel('Error [dB]')
title('Validation statistics by frequency')
legend('Location','best')

%% ============================================================
%  PLOT 4 - SOURCE DIRECTIVITY
% =============================================================

figure

for j = 1:nFreq

    subplot(2,4,j)

    thetaPlot = ...
        [calibAnglesDeg(:); ...
         calibAnglesDeg(1)+360];

    Dplot = ...
        [D_source(:,j); ...
         D_source(1,j)];

    polarplot( ...
        deg2rad(thetaPlot), ...
        Dplot, ...
        'o-', ...
        'LineWidth',1.5)

    title(sprintf('%d Hz',f(j)))

end

%% ============================================================
%  SAVE SOURCE MODEL FOR FUTURE PREDICTIONS
% =============================================================

sourceModel = struct;

sourceModel.f = f;
sourceModel.L_W = L_W;
sourceModel.L_W_std = L_W_std;

sourceModel.calibAnglesDeg = calibAnglesDeg;
sourceModel.D_source = D_source;

sourceModel.h_s = h_s;

sourceModel.closeMics = closeMics;
sourceModel.farMics = farMics;
sourceModel.micsToUse = micsToUse;

sourceModel.T_C_experiment = T_C;
sourceModel.RH_experiment = RH;
sourceModel.p_experiment = p;

sourceModel.experimentFolder = experimentFolder;

save( ...
    outputMAT, ...
    'sourceModel', ...
    'results', ...
    'SourceTable', ...
    'DirectivityTable', ...
    'ValidationSummary', ...
    'ValidationFrequency', ...
    'Lp_total_all', ...
    'Lp_bg_all', ...
    'A_div_far', ...
    'A_atm_far', ...
    'A_gr_far', ...
    'A_bar_far');

%% ============================================================
%  EXPORT EXCEL
% =============================================================

if isfile(outputExcel)
    delete(outputExcel)
end

writetable( ...
    SourceTable, ...
    outputExcel, ...
    'Sheet','Source');

writetable( ...
    DirectivityTable, ...
    outputExcel, ...
    'Sheet','Directivity');

writetable( ...
    ValidationSummary, ...
    outputExcel, ...
    'Sheet','Validation Summary');

writetable( ...
    ValidationFrequency, ...
    outputExcel, ...
    'Sheet','Validation Frequency');

%% Per-mic spectra

for i = 1:nFar

    mic = farMics(i);

    MicTable = table( ...
        f.', ...
        results.Lp_measured(i,:).', ...
        results.Lp_predicted(i,:).', ...
        results.Delta_L(i,:).', ...
        results.D_source_est(i,:).', ...
        results.A_div(i,:).', ...
        results.A_atm(i,:).', ...
        results.A_gr(i,:).', ...
        results.A_bar(i,:).', ...
        'VariableNames',{ ...
            'f_Hz', ...
            'Lp_measured', ...
            'Lp_predicted', ...
            'Delta_L', ...
            'D_source', ...
            'A_div', ...
            'A_atm', ...
            'A_gr', ...
            'A_bar'});

    writetable( ...
        MicTable, ...
        outputExcel, ...
        'Sheet',sprintf('Mic_%02d',mic));

end

fprintf('\n============================================\n')
fprintf('FILES SAVED\n')
fprintf('============================================\n')

fprintf('MAT model:\n%s\n\n',outputMAT)
fprintf('Excel report:\n%s\n',outputExcel)